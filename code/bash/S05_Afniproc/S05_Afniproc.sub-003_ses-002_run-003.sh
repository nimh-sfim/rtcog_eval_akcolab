#!/bin/tcsh -xef

echo "auto-generated by afni_proc.py, Fri Nov  6 15:11:52 2026"
echo "(version 8.12, November 4, 2026)"
echo "execution started: `date`"

# to execute via tcsh: 
#   tcsh -xef /data/SFIMJGC_CLARID/AKColab/code/bash//S05_Afniproc/S05_Afniproc.sub-003_ses-002_run-003.sh |& tee /data/SFIMJGC_CLARID/AKColab/code/bash//S05_Afniproc/output.S05_Afniproc.sub-003_ses-002_run-003.sh
# to execute via bash: 
#   tcsh -xef /data/SFIMJGC_CLARID/AKColab/code/bash//S05_Afniproc/S05_Afniproc.sub-003_ses-002_run-003.sh 2>&1 | tee /data/SFIMJGC_CLARID/AKColab/code/bash//S05_Afniproc/output.S05_Afniproc.sub-003_ses-002_run-003.sh

# =========================== auto block: setup ============================
# script setup

# take note of the AFNI version
afni -ver

# check that the current AFNI version is recent enough
afni_history -check_date  7 Jan 2026
if ( $status ) then
    echo "** this script requires newer AFNI binaries (than  7 Jan 2026)"
    echo "   (consider: @update.afni.binaries -defaults)"
    exit
endif

# the user may specify a single subject to run with
if ( $#argv > 0 ) then
    set subj = $argv[1]
else
    set subj = sub-003
endif

# assign output directory name
set output_dir = /data/SFIMJGC_CLARID/AKColab/prcs_data//sub-003/ses-002/D03_afniproc_run-003

# verify that the results directory does not yet exist
if ( -d $output_dir ) then
    echo output dir "$output_dir" already exists
    exit
endif

# set list of runs
set runs = (`count_afni -digits 2 1 1`)

# create results and stimuli directories
mkdir -p $output_dir
mkdir $output_dir/stimuli

# copy anatomy to results dir
3dcopy                                                                                  \
    /data/SFIMJGC_CLARID/AKColab/prcs_data/sub-003/D01_Anatomical/anatSS.sub-003.nii.gz \
    $output_dir/anatSS.sub-003

# copy external blip NL warp (transformation) dataset
3dcopy                                                                                                                                            \
    /data/SFIMJGC_CLARID/AKColab/prcs_data/sub-003/ses-002/D04_BiasField_run-003/sub-003_ses-002_task-ExperienceSampling_run-003_bold_WARP.nii.gz \
    $output_dir/distortion_warp

# ============================ auto block: tcat ============================
# apply 3dTcat to copy input dsets to results dir,
# while removing the first 0 TRs
3dTcat -prefix $output_dir/pb00.$subj.r01.tcat                     \
    /data/SFIMJGC_CLARID/AKColab/prcs_data/sub-003/ses-002/D03_OrigData_SlTimeCorr/sub-003_ses-002_task-ExperienceSampling_run-003_bold.nii.gz'[0..$]'

# and make note of repetitions (TRs) per run
set tr_counts = ( 313 )

# -------------------------------------------------------
# enter the results directory (can begin processing data)
cd $output_dir


# -------------------------------------------------------
# QC - GTKYD: get to know your data: generate attribute files
gtkyd_check.py -infiles pb00.*.HEAD -outdir gtkyd

# -------------------------------------------------------
# QC - GTKYD: check for varying data type across EPI inputs
gen_ss_review_table.py -infiles gtkyd/dset*.txt -outlier_sep space \
    -report_outliers datum VARY                                    \
    -report_outliers orient VARY                                   \
    -report_outliers av_space VARY                                 \
    |& tee out.gtkyd.outliers.txt

# ---------------------------------------------------------
# QC: look for columns of high variance
find_variance_lines.tcsh -polort 5                                 \
       -rdir vlines.pb00.tcat                                      \
       pb00.$subj.r*.tcat+orig.HEAD |& tee out.vlines.pb00.tcat.txt

# ========================== auto block: outcount ==========================
# QC: compute outlier fraction for each volume
touch out.pre_ss_warn.txt
foreach run ( $runs )
    3dToutcount -automask -fraction -polort 5 -legendre                     \
                pb00.$subj.r$run.tcat+orig > outcount.r$run.1D

    # outliers at TR 0 might suggest pre-steady state TRs
    if ( `1deval -a outcount.r$run.1D"{0}" -expr "step(a-0.4)"` ) then
        echo "** TR #0 outliers: possible pre-steady state TRs in run $run" \
            >> out.pre_ss_warn.txt
    endif
end

# catenate outlier counts into a single time series
cat outcount.r*.1D > outcount_rall.1D

# ---------------------------------------------------------
# check for potential 4095 saturation issues
foreach run ( $runs )
    3dTto1D -method 4095_warn -input pb00.$subj.r$run.tcat+orig             \
            |& tee -a out.4095_all.txt
end

# make a file showing any resulting warnings
awk '/warning/ {print}' out.4095_all.txt | tee out.4095_warn.txt

# ================================= tshift =================================
# time shift data so all slice timing is the same 
foreach run ( $runs )
    3dTshift -tzero 0 -wsinc9 -prefix pb01.$subj.r$run.tshift \
             pb00.$subj.r$run.tcat+orig
end

# ================================== blip ==================================
# apply non-linear EPI distortion correction


# no computation to do: have external -blip_warp_dset distortion_warp+orig

# warp EPI time series data
foreach run ( $runs )
    3dNwarpApply -quintic -nwarp distortion_warp+orig \
                 -source pb01.$subj.r$run.tshift+orig \
                 -prefix pb02.$subj.r$run.blip
    3drefit -atrcopy pb01.$subj.r$run.tshift+orig     \
                     IJK_TO_DICOM_REAL                \
                     pb02.$subj.r$run.blip+orig
end

# --------------------------------
# extract volreg registration base
3dbucket -prefix vr_base pb02.$subj.r01.blip+orig"[0]"

# ================================= align ==================================
# a2e: align anatomy to EPI registration base
# (new anat will be aligned and stripped, anatSS.sub-003_al_keep+orig)
# run (localized) uniformity correction on EPI base
3dLocalUnifize -input vr_base+orig -prefix vr_base_unif

align_epi_anat.py -anat2epi -anat anatSS.sub-003+orig \
       -suffix _al_keep                               \
       -epi vr_base_unif+orig -epi_base 0             \
       -epi_strip 3dAutomask                          \
       -anat_has_skull no                             \
       -cost lpc+ZZ -giant_move -check_flip           \
       -volreg off -tshift off

# ================================= volreg =================================
# align each dset to base volume, blip warp
# (final warp input is same as blip input)
foreach run ( $runs )
    # register each volume to the base image
    3dvolreg -verbose -zpad 1 -base vr_base+orig                       \
             -1Dfile dfile.r$run.1D -prefix rm.epi.volreg.r$run        \
             -cubic                                                    \
             -1Dmatrix_save mat.r$run.vr.aff12.1D                      \
             pb02.$subj.r$run.blip+orig

    # catenate blip/volreg xforms
    cat_matvec -ONELINE                                                \
               mat.r$run.vr.aff12.1D > mat.r$run.warp.aff12.1D

    # apply catenated xform: blip/volreg
    3dNwarpApply                                                       \
                 -source pb01.$subj.r$run.tshift+orig                  \
                 -nwarp "mat.r$run.warp.aff12.1D distortion_warp+orig" \
                 -ainterp wsinc5                                       \
                 -prefix pb03.$subj.r$run.volreg
end

# make a single file of registration params
cat dfile.r*.1D > dfile_rall.1D

# compute motion magnitude time series: the Euclidean norm
# (sqrt(sum squares)) of the motion parameter derivatives
1d_tool.py -infile dfile_rall.1D -set_nruns 1                          \
           -derivative -collapse_cols euclidean_norm                   \
           -write motion_${subj}_enorm.1D

# create an anat_final dataset, aligned with stats
3dcopy anatSS.sub-003_al_keep+orig anat_final.$subj

# --------------------------------------
# create a TSNR dataset, just from run 1
3dTstat -mean -prefix rm.signal.vreg.r01 pb03.$subj.r01.volreg+orig
3dDetrend -polort 5 -prefix rm.noise.det -overwrite pb03.$subj.r01.volreg+orig
3dTstat -stdev -prefix rm.noise.vreg.r01 rm.noise.det+orig
3dcalc -a rm.signal.vreg.r01+orig                                      \
       -b rm.noise.vreg.r01+orig                                       \
       -expr 'a/b' -prefix TSNR.vreg.r01.$subj

# ========================= auto block: QC_review ==========================
# generate quality control review scripts

# generate a review script for the unprocessed EPI data
gen_epi_review.py -script @epi_review.$subj \
    -dsets pb00.$subj.r*.tcat+orig.HEAD

# ========================== auto block: finalize ==========================

# remove temporary files
\rm -f rm.*

# --------------------------------------------------
# if the basic subject review script is here, run it
# (want this to be the last text output)
if ( -e @ss_review_basic ) then
    ./@ss_review_basic |& tee out.ss_review.$subj.txt
endif

# return to parent directory (just in case...)
cd ..

echo "execution finished: `date`"




